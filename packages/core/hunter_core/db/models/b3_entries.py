"""The B3 entry chain — proposal, intent (machine B) and the event receipts —
DATABASE.md §74, ``docs/RISK_ENGINE_B3.md`` §3, §6.7.

``b3_entry_proposals`` is the immutable ``B3EntryProposal`` (§8.1), one per
``(strategy_key, strategy_version, session_date, window_id)`` (§3.1, "uma proposta
por janela"). ``b3_entry_intents`` is its state machine, keyed on the same
``proposal_id``: the decision is written once, the claim is written once, and
``client_order_id`` is a stored column **generated by the database** from
``proposal_id`` (``b3_client_order_id``, the §1.1 formula), unique — I-E-4 holds
by construction. The transitions of §3.1/§6 and the identity half of the claim
(§3.3) live in a trigger of ``0071_b3_robot`` (``ddl/b3_robot_guards.py``).
"""

from __future__ import annotations

import uuid
from datetime import date, datetime
from decimal import Decimal
from typing import Any

from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    Computed,
    ForeignKeyConstraint,
    Index,
    Text,
    UniqueConstraint,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column

from hunter_core.db.base import Base, TenantMixin, UUIDPrimaryKeyMixin
from hunter_core.db.models._common import org_fk, pg_enum
from hunter_core.db.models.b3_robot import account_fk, instance_fk
from hunter_core.domain.b3_enums import B3EntryIntentStatus, B3UnknownCause
from hunter_core.domain.enums import OrderSide

OPEN_INTENT = (
    "status IN ('proposed', 'approved', 'submitting', 'working', 'partially_filled', "
    "'cancel_requested', 'unknown')"
)
"""§3.1: the states that block a new entry (check 11) and are never re-sent."""

POST_CLAIM = (
    "('submitting', 'aborted_before_send', 'working', 'partially_filled', 'filled', "
    "'cancel_requested', 'canceled', 'broker_rejected', 'unknown', 'resolved_manual')"
)
"""Every state only a won claim can reach."""

APPROVED_LINE = POST_CLAIM[:-1] + ", 'approved')"
"""``approved`` and everything after it: the states that carry an approval."""

_APPROVAL_COLUMNS = ("expires_at", "limits_version", "grid_version", "spec_pin_id", "n_final")

DECISION_MIRRORS_COLUMNS = (
    "decision IS NULL OR ("
    "decision ?& ARRAY['proposal_id', 'approved', 'reasons', 'checks', 'sizing', "
    "'kill_switch_effective', 'triggers', 'limits_version', 'grid_version', 'spec_pin_id', "
    "'as_of', 'approved_at', 'expires_at'] "
    "AND jsonb_array_length(decision -> 'checks') = 25 "
    "AND decision ->> 'proposal_id' = proposal_id::text "
    "AND (decision ->> 'approved')::boolean = (approved_at IS NOT NULL) "
    "AND (approved_at IS NULL OR ("
    "decision ->> 'limits_version' = limits_version::text "
    "AND decision ->> 'grid_version' = grid_version::text "
    "AND decision ->> 'spec_pin_id' = spec_pin_id::text "
    "AND (decision #>> '{sizing,n_final}')::numeric = n_final "
    "AND (decision #>> '{sizing,limit_price}')::numeric = limit_price "
    "AND (decision ->> 'as_of')::timestamptz = approved_at "
    "AND (decision ->> 'approved_at')::timestamptz = approved_at "
    "AND (decision ->> 'expires_at')::timestamptz = expires_at))"
    ") IS TRUE"
)
"""The persisted ``RiskDecision`` (``hunter_risk_b3.decision``, contract §8.4, R1's field
names) and the columns the claim reads are the same decision: 25 checks, this proposal,
``approved`` iff the approval columns are set, and the versions, spec pin, ``n_final``,
``limit_price`` and the instants (``as_of = approved_at``, ``expires_at``) equal — a late
first write cannot re-date an approval. ``IS TRUE`` because a missing key makes a comparison
NULL, and a NULL CHECK passes — R1 serializes ``limits_version``/``grid_version``/``spec_pin_id``
as strings, so the comparison is on ``::text``."""


class B3EntryProposal(Base, TenantMixin):
    """``b3_entry_proposals`` — the ``B3EntryProposal`` of §8.1, append-only."""

    __tablename__ = "b3_entry_proposals"
    __table_args__ = (
        org_fk(),
        account_fk(),
        instance_fk(),
        UniqueConstraint(
            "organization_id",
            "strategy_key",
            "strategy_version",
            "session_date",
            "window_id",
            name="uq_b3_entry_proposals_window",
        ),
        UniqueConstraint(
            "organization_id",
            "proposal_id",
            "instance_id",
            "account_hash",
            name="uq_b3_entry_proposals_identity",
        ),
        Index("ix_b3_entry_proposals_session", "organization_id", "session_date"),
        Index("ix_b3_entry_proposals_account", "organization_id", "account_hash", "created_at"),
        Index("ix_b3_entry_proposals_instance", "organization_id", "instance_id"),
        CheckConstraint("requested_contracts >= 1", name="requested_contracts_positive"),
        CheckConstraint("ref_price > 0 AND stop_price > 0", name="prices_are_positive"),
        CheckConstraint("target_price IS NULL OR target_price > 0", name="target_is_positive"),
        CheckConstraint(
            "entry_window_start_utc <= entry_window_end_utc", name="entry_window_order"
        ),
    )

    proposal_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True)
    account_hash: Mapped[str] = mapped_column(Text)
    instance_id: Mapped[uuid.UUID]
    strategy_key: Mapped[str] = mapped_column(Text)
    strategy_version: Mapped[int]
    params_hash: Mapped[str] = mapped_column(Text)
    session_date: Mapped[date]
    window_id: Mapped[str] = mapped_column(Text)
    symbol: Mapped[str] = mapped_column(Text)
    side: Mapped[OrderSide] = mapped_column(pg_enum("order_side"))
    requested_contracts: Mapped[int]
    ref_price: Mapped[Decimal]
    stop_price: Mapped[Decimal]
    target_price: Mapped[Decimal | None]
    exit_at_utc: Mapped[datetime | None]
    signal_published_at: Mapped[datetime]
    signal_deadline_utc: Mapped[datetime]
    entry_window_start_utc: Mapped[datetime]
    entry_window_end_utc: Mapped[datetime]
    created_at: Mapped[datetime] = mapped_column(server_default=func.now())


class B3EntryIntent(Base, TenantMixin):
    """``b3_entry_intents`` — machine B (§3.1), one row per proposal."""

    __tablename__ = "b3_entry_intents"
    __table_args__ = (
        org_fk(),
        ForeignKeyConstraint(
            ["organization_id", "proposal_id", "instance_id", "account_hash"],
            [
                "b3_entry_proposals.organization_id",
                "b3_entry_proposals.proposal_id",
                "b3_entry_proposals.instance_id",
                "b3_entry_proposals.account_hash",
            ],
            ondelete="CASCADE",
        ),
        ForeignKeyConstraint(
            ["organization_id", "account_hash", "spec_pin_id"],
            ["b3_spec_pins.organization_id", "b3_spec_pins.account_hash", "b3_spec_pins.id"],
            ondelete="RESTRICT",
        ),
        UniqueConstraint("client_order_id", name="uq_b3_entry_intents_client_order_id"),
        UniqueConstraint(
            "organization_id", "account_hash", "proposal_id", name="uq_b3_entry_intents_account"
        ),
        Index(
            "ix_b3_entry_intents_open",
            "organization_id",
            "account_hash",
            postgresql_where=text(OPEN_INTENT),
        ),
        Index("ix_b3_entry_intents_org_status", "organization_id", "status", "created_at"),
        Index("ix_b3_entry_intents_spec_pin", "organization_id", "account_hash", "spec_pin_id"),
        CheckConstraint("(decided_at IS NULL) = (decision IS NULL)", name="decision_is_whole"),
        CheckConstraint("status <> 'proposed' OR decided_at IS NULL", name="proposed_undecided"),
        CheckConstraint(
            "status <> 'rejected' OR (decided_at IS NOT NULL AND approved_at IS NULL)",
            name="rejected_is_decided_unapproved",
        ),
        CheckConstraint(
            " AND ".join(f"(approved_at IS NULL) = ({c} IS NULL)" for c in _APPROVAL_COLUMNS)
            + " AND (approved_at IS NULL) = (limit_price IS NULL)",
            name="approval_is_whole",
        ),
        CheckConstraint(
            "approved_at IS NULL OR decided_at IS NOT NULL", name="approval_is_a_decision"
        ),
        # §3.2/§8.4: expires_at = as_of + 30 s, approved_at = as_of — the house rule.
        CheckConstraint(
            "approved_at IS NULL OR expires_at = approved_at + interval '30 seconds'",
            name="approval_lives_30_seconds",
        ),
        CheckConstraint(
            f"status NOT IN {APPROVED_LINE} OR approved_at IS NOT NULL",
            name="approved_before_claim",
        ),
        CheckConstraint(
            "(claimed_at IS NULL) = (claim_instance_id IS NULL) "
            "AND (claimed_at IS NULL) = (claim_fencing_token IS NULL) "
            "AND (claimed_at IS NULL) = (send_deadline_utc IS NULL)",
            name="claim_is_whole",
        ),
        CheckConstraint(
            f"(status IN {POST_CLAIM}) = (claimed_at IS NOT NULL)", name="claimed_iff_post_claim"
        ),
        CheckConstraint(
            "claim_instance_id IS NULL OR claim_instance_id = instance_id",
            name="claimed_by_the_proposing_instance",
        ),
        CheckConstraint(
            "send_deadline_utc IS NULL OR send_deadline_utc <= expires_at",
            name="send_deadline_within_approval",
        ),
        CheckConstraint("status <> 'unknown' OR unknown_cause IS NOT NULL", name="unknown_cause"),
        CheckConstraint(
            "(status = 'resolved_manual') = (resolved_at IS NOT NULL) "
            "AND (resolved_at IS NULL) = (resolved_by IS NULL) "
            "AND (resolved_at IS NULL OR (resolved_note IS NOT NULL "
            "AND length(btrim(resolved_note)) > 0))",
            name="manual_resolution_is_whole",
        ),
        CheckConstraint("n_final IS NULL OR n_final >= 1", name="n_final_at_least_one"),
        CheckConstraint("limit_price IS NULL OR limit_price > 0", name="limit_price_positive"),
        CheckConstraint(
            "filled_volume IS NULL OR (filled_volume >= 0 AND filled_volume <= n_final)",
            name="filled_within_approval",
        ),
        CheckConstraint(
            "decision IS NULL OR jsonb_typeof(decision) = 'object'", name="decision_is_an_object"
        ),
        CheckConstraint(DECISION_MIRRORS_COLUMNS, name="decision_matches_its_columns"),
    )

    proposal_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True)
    account_hash: Mapped[str] = mapped_column(Text)
    instance_id: Mapped[uuid.UUID]
    status: Mapped[B3EntryIntentStatus] = mapped_column(
        pg_enum("b3_entry_intent_status"), server_default=B3EntryIntentStatus.PROPOSED.value
    )
    decision: Mapped[dict[str, Any] | None] = mapped_column(JSONB)
    decided_at: Mapped[datetime | None]
    approved_at: Mapped[datetime | None]
    expires_at: Mapped[datetime | None]
    limits_version: Mapped[int | None]
    grid_version: Mapped[int | None]
    spec_pin_id: Mapped[uuid.UUID | None]
    n_final: Mapped[Decimal | None]
    limit_price: Mapped[Decimal | None]
    claimed_at: Mapped[datetime | None]
    claim_instance_id: Mapped[uuid.UUID | None]
    claim_fencing_token: Mapped[int | None] = mapped_column(BigInteger)
    send_deadline_utc: Mapped[datetime | None]
    client_order_id: Mapped[str] = mapped_column(
        Text, Computed("b3_client_order_id(proposal_id)", persisted=True)
    )
    broker_order_ticket: Mapped[int | None] = mapped_column(BigInteger)
    filled_volume: Mapped[Decimal | None]
    unknown_cause: Mapped[B3UnknownCause | None] = mapped_column(pg_enum("b3_unknown_cause"))
    terminal_reason: Mapped[str | None] = mapped_column(Text)
    resolved_at: Mapped[datetime | None]
    resolved_by: Mapped[uuid.UUID | None]
    resolved_note: Mapped[str | None] = mapped_column(Text)
    created_at: Mapped[datetime] = mapped_column(server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(server_default=func.now(), onupdate=func.now())


class B3RobotEvent(Base, UUIDPrimaryKeyMixin, TenantMixin):
    """``b3_robot_events`` — the ingestion receipt of every robot event (§6.7).

    The API writes it in the same transaction as the event's effects, keyed on the
    robot's ``event_id`` (``Idempotency-Key``): a replay of the outage buffer, or
    a retry after a lost response, finds the receipt and applies nothing twice.
    Unique per organization, never global (DATABASE.md §15.3). Append-only; not
    audited itself — the effects are.
    """

    __tablename__ = "b3_robot_events"
    __table_args__ = (
        org_fk(),
        account_fk(),
        instance_fk(),
        UniqueConstraint("organization_id", "event_id", name="uq_b3_robot_events_event"),
        Index("ix_b3_robot_events_account", "organization_id", "account_hash", "received_at"),
        Index("ix_b3_robot_events_instance", "organization_id", "instance_id"),
        CheckConstraint("payload_sha256 ~ '^[0-9a-f]{64}$'", name="payload_sha256_is_hex"),
    )

    event_id: Mapped[uuid.UUID]
    account_hash: Mapped[str] = mapped_column(Text)
    instance_id: Mapped[uuid.UUID]
    kind: Mapped[str] = mapped_column(Text)
    payload_sha256: Mapped[str] = mapped_column(Text)
    received_at: Mapped[datetime] = mapped_column(server_default=func.now())
